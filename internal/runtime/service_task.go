package runtime

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// RenderWindowsTaskRegistration generates an explicit, reviewable registration
// script. Generating it never registers, starts, or replaces a scheduled task.
func RenderWindowsTaskRegistration(paths Paths, instance, executable string) (string, error) {
	if err := ValidateInstanceName(instance); err != nil {
		return "", err
	}
	for _, path := range []string{paths.Home, executable} {
		if !filepath.IsAbs(path) || strings.ContainsAny(path, "\"\x00\r\n") {
			return "", fmt.Errorf("task paths must be absolute and contain no quotes or control characters")
		}
	}
	args := "daemon --instance " + instance + " --home " + quoteWindowsArgument(paths.Home)
	return "# Generated by agent-harness; review before running. No credentials are stored here.\r\n" +
		"$ErrorActionPreference = 'Stop'\r\n" +
		"$sid = [System.Security.Principal.WindowsIdentity]::GetCurrent().User.Value\r\n" +
		"$instanceHome = " + powershellLiteral(paths.Home) + "\r\n" +
		"$action = New-ScheduledTaskAction -Execute " + powershellLiteral(executable) + " -Argument " + powershellLiteral(args) + " -WorkingDirectory $instanceHome\r\n" +
		"$trigger = New-ScheduledTaskTrigger -AtLogOn -User $sid\r\n" +
		"$principal = New-ScheduledTaskPrincipal -UserId $sid -LogonType Interactive -RunLevel Limited\r\n" +
		"$settings = New-ScheduledTaskSettingsSet -MultipleInstances IgnoreNew -ExecutionTimeLimit ([TimeSpan]::Zero) -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1) -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries\r\n" +
		"Register-ScheduledTask -TaskName " + powershellLiteral("agent-harness-"+instance) + " -Action $action -Trigger $trigger -Principal $principal -Settings $settings\r\n", nil
}

func powershellLiteral(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

// No shell parses these arguments. Double trailing backslashes for the Windows
// command-line parser so even an explicit drive-root home round-trips correctly.
func quoteWindowsArgument(s string) string {
	trailing := len(s) - len(strings.TrimRight(s, "\\"))
	return "\"" + s + strings.Repeat("\\", trailing) + "\""
}

func InstallWindowsTask(paths Paths, instance, executable string) (string, error) {
	script, err := RenderWindowsTaskRegistration(paths, instance, executable)
	if err != nil {
		return "", err
	}
	if err := InitInstance(paths); err != nil {
		return "", err
	}
	path := filepath.Join(paths.ConfigDir, "register-task.ps1")
	// Windows PowerShell 5.1 interprets UTF-8 without a BOM as the ANSI code page.
	if err := os.WriteFile(path, append([]byte{0xef, 0xbb, 0xbf}, []byte(script)...), 0600); err != nil {
		return "", err
	}
	return path, nil
}
